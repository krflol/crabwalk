CODEGEN_SCHEMA_VERSION = 45

_NATIVE_EXCEPTION_TYPES = (
    (NATIVE_MOVE_ERROR, "__CwNativeMoveError"),
    (NATIVE_BORROW_ERROR, "__CwNativeBorrowError"),
    (NATIVE_PANIC_ERROR, "__CwNativePanicError"),
    (NATIVE_RUST_RESULT_ERROR, "__CwNativeRustResultError"),
)


@dataclass(frozen=True, slots=True)
class GeneratedProject:
    cargo_toml: str
    build_rs: str
    rust_source: str
    source_map: dict[str, object]
    ir_json: str


def generate_project(
    ir: PackageIR,
    extension_name: str,
    *,
    cargo_package_identity: str | None = None,
) -> GeneratedProject:
    from .validation import validate_package_ir

    validate_package_ir(ir)
    writer = _Writer()
    domains_by_symbol = {value.symbol: value.type_ref for value in ir.structs}
    domains_by_symbol.update({value.symbol: value.type_ref for value in ir.enums})
    structs_by_symbol = {value.symbol: value for value in ir.structs}
    enums_by_symbol = {value.symbol: value for value in ir.enums if not value.is_error}
    error_enums_by_symbol = {
        value.symbol: value for value in ir.enums if value.is_error
    }
    boundary_names = {
        function.rust_symbol for function in ir.functions if function.python_boundary
    }
    writer.line("// Generated by Crabwalk. Inspectable; do not edit.")
    writer.line(
        f"// IR schema: {ir.schema_version}; codegen schema: {CODEGEN_SCHEMA_VERSION}"
    )
    writer.line(f"extern crate {PYO3_CARGO_ALIAS} as pyo3;")
    for dependency in sorted(ir.crates, key=lambda value: value.binding):
        cargo_key = cargo_dependency_key(dependency.package, dependency.binding)
        writer.line(f"extern crate {cargo_key} as {dependency.binding};")
    writer.line(f"use {PYO3_CARGO_ALIAS}::prelude::*;")
    if ir.structs or any(_enum_has_heterogeneous_fields(value) for value in ir.enums):
        writer.line(f"use {PYO3_CARGO_ALIAS}::IntoPyObjectExt;")
    for dependency in sorted(ir.crates, key=lambda value: value.binding):
        if dependency.package == "rayon":
            writer.line(f"use {dependency.binding}::prelude::*;")
    writer.line("mod __crabwalk_ffi {")
    writer.enter()
    writer.line('unsafe extern "C" {')
    writer.enter()
    writer.line('#[link_name = "abs"]')
    writer.line("pub(super) fn c_abs(input: i32) -> i32;")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line()
    _write_native_exceptions(writer)
    writer.line()
    _write_panic_boundary(writer)
    writer.line()
    if any(
        parameter.type_ref.underlying.rust_name == "Buffer"
        for function in ir.functions
        for parameter in function.parameters
    ):
        _write_buffer_support(writer)
        writer.line()
    owned_text_column = _owned_text_column_type(ir)
    if owned_text_column is not None:
        _write_text_column_support(writer, owned_text_column)
        writer.line()
    _write_thread_pool(writer)
    writer.line()

    if any(function.is_async for function in ir.functions):
        _write_block_on_executor(writer)
        writer.line()

    for trait in ir.traits:
        if trait.external_path is None:
            _write_native_trait(writer, trait)
            writer.line()

    for enum in ir.enums:
        _write_native_enum(writer, enum)
        writer.line()
        if enum.is_error:
            _write_native_error_impls(writer, enum)
        else:
            _write_owned_enum_class(writer, enum, domains_by_symbol)
        writer.line()

    for struct in ir.structs:
        _write_native_struct(writer, struct)
        writer.line()
        _write_owned_struct_class(writer, struct, domains_by_symbol)
        writer.line()

    owned_vectors = _owned_vector_types(ir)
    domain_vector_elements = tuple(
        value.arguments[0]
        for value in owned_vectors
        if _contains_domain(value.arguments[0], domains_by_symbol)
    )
    if domain_vector_elements:
        _write_bulk_input_extractors(
            writer,
            domain_vector_elements,
            structs_by_symbol,
            enums_by_symbol,
        )
        writer.line()
    for vector_type in owned_vectors:
        _write_owned_vector_class(
            writer,
            vector_type,
            domains_by_symbol,
        )
        writer.line()

    owned_external_types = _owned_external_types(ir)
    for external_type in owned_external_types:
        _write_owned_external_class(writer, external_type)
        writer.line()

    shared_types = _shared_types(ir)
    for shared_type in shared_types:
        _write_shared_class(writer, shared_type)
        writer.line()

    for function in ir.functions:
        _write_native_function(writer, function, boundary_names)
        writer.line()

    _write_method_impls(writer, ir)

    for function in ir.functions:
        if function.exported:
            _write_export_wrapper(
                writer,
                function,
                boundary_names,
                error_enums_by_symbol,
            )
            writer.line()

    writer.line(f'#[pymodule(name = "{extension_name}")]')
    writer.line("fn __crabwalk_module(m: &Bound<'_, PyModule>) -> PyResult<()> {")
    writer.enter()
    for python_name, rust_name in _NATIVE_EXCEPTION_TYPES:
        writer.line(f'm.add("{python_name}", m.py().get_type::<{rust_name}>())?;')
    for function in ir.functions:
        if not function.exported:
            continue
        writer.line(
            f"m.add_function({PYO3_CARGO_ALIAS}::wrap_pyfunction!({function.rust_symbol}, m)?)?;",
            function.span,
            "abi_export",
        )
    for vector_type in owned_vectors:
        _, rust_class = owned_class_names(vector_type)
        writer.line(f"m.add_class::<{rust_class}>()?;")
    for external_type in owned_external_types:
        _, rust_class = owned_class_names(external_type)
        writer.line(f"m.add_class::<{rust_class}>()?;")
    if owned_text_column is not None:
        _, rust_class = owned_class_names(owned_text_column)
        writer.line(f"m.add_class::<{rust_class}>()?;")
    for shared_type in shared_types:
        _, rust_class = shared_class_names(shared_type)
        writer.line(f"m.add_class::<{rust_class}>()?;")
    for struct in ir.structs:
        _, rust_class = owned_class_names(struct.type_ref)
        writer.line(f"m.add_class::<{rust_class}>()?;")
    for enum in ir.enums:
        if enum.is_error:
            continue
        _, rust_class = owned_class_names(enum.type_ref)
        writer.line(f"m.add_class::<{rust_class}>()?;")
    writer.line("std::result::Result::Ok(())")
    writer.leave()
    writer.line("}")

    source_map = {
        "schema_version": 2,
        "generated_file": "src/lib.rs",
        "source_hash": ir.source_hash,
        "compiler_input_hash": ir.compiler_input_hash,
        "wheel_source_integrity_hash": ir.wheel_source_integrity_hash,
        "entries": writer.mappings,
    }
    return GeneratedProject(
        cargo_toml=render_cargo_toml(
            ir,
            extension_name,
            cargo_package_identity,
        ),
        build_rs=render_build_rs(extension_name),
        rust_source=writer.render(),
        source_map=source_map,
        ir_json=json.dumps(ir.to_dict(), indent=2, sort_keys=True) + "\n",
    )


def _write_native_struct(writer: _Writer, struct: StructIR) -> None:
    derives = ["Clone", "Debug"] + ["::".join(value) for value in struct.derives]
    writer.line(f"#[derive({', '.join(derives)})]", struct.span, "struct_derive")
    writer.line(f"struct {struct.symbol} {{", struct.span, "struct")
    writer.enter()
    for field in struct.fields:
        writer.line(
            f"pub {field.rust_name}: {field.type_ref.render()},",
            field.span,
            "struct_field",
        )
    writer.leave()
    writer.line("}")


def _write_native_trait(writer: _Writer, trait: TraitIR) -> None:
    writer.line(f"trait {trait.symbol} {{", trait.span, "trait")
    writer.enter()
    associated_names: set[str] = set()

    def collect_associated(type_ref: TypeRef) -> None:
        if type_ref.rust_name == "Associated" and type_ref.python_name is not None:
            associated_names.add(type_ref.python_name)
        for argument in type_ref.arguments:
            collect_associated(argument)

    for method in trait.methods:
        collect_associated(method.return_type)
        for parameter_type in method.parameter_types:
            collect_associated(parameter_type)
    for name in sorted(associated_names):
        writer.line(f"type {name};", trait.span, "trait_associated_type")
    if associated_names:
        writer.line()
    for method in trait.methods:
        rendered_generics: list[str] = []
        for parameter in method.type_parameters:
            if parameter.is_lifetime:
                rendered_generics.append(f"'{parameter.rust_name}")
            else:
                bounds = f": {' + '.join(parameter.bounds)}" if parameter.bounds else ""
                rendered_generics.append(f"{parameter.rust_name}{bounds}")
        generics = f"<{', '.join(rendered_generics)}>" if rendered_generics else ""
        receiver = {
            "Ref": "&self",
            "Mut": "&mut self",
            "Owned": "self",
        }[method.receiver_ownership]
        parameters = tuple(
            f"__cw_trait_arg_{index}: {type_ref.render()}"
            for index, type_ref in enumerate(method.parameter_types)
        )
        signature = ", ".join((receiver, *parameters))
        writer.line(
            f"fn {method.rust_name}{generics}({signature}) "
            f"-> {method.return_type.render()};",
            method.span,
            "trait_method",
        )
    writer.leave()
    writer.line("}")


def _write_method_impls(writer: _Writer, package: PackageIR) -> None:
    traits_by_symbol = {trait.symbol: trait for trait in package.traits}
    trait_method_names = {
        (trait.symbol, method.name): method.rust_name
        for trait in package.traits
        for method in trait.methods
    }
    inherent = [
        function
        for function in package.functions
        if function.method_for is not None
        and function.trait_symbol is None
        and function.operator_kind is None
    ]
    for function in inherent:
        assert function.method_for is not None and function.method_name is not None
        writer.line(f"impl {function.method_for.render()} {{")
        writer.enter()
        _write_method_glue(writer, function)
        writer.leave()
        writer.line("}")
        writer.line()

    operators = [
        function
        for function in package.functions
        if function.method_for is not None and function.operator_kind is not None
    ]
    for function in operators:
        assert function.method_for is not None
        assert function.operator_kind is not None
        assert len(function.parameters) == 2
        trait_name, method_name = {
            "add": ("Add", "add"),
            "subtract": ("Sub", "sub"),
            "multiply": ("Mul", "mul"),
            "divide": ("Div", "div"),
            "remainder": ("Rem", "rem"),
        }[function.operator_kind]
        right = function.parameters[1]
        writer.line(
            f"impl std::ops::{trait_name}<{right.type_ref.render()}> "
            f"for {function.method_for.render()} {{"
        )
        writer.enter()
        writer.line(f"type Output = {function.return_type.render()};")
        writer.line()
        writer.line(
            f"fn {method_name}(self, {right.rust_name}: {right.type_ref.render()}) "
            "-> Self::Output {",
            function.span,
            "operator_impl",
        )
        writer.enter()
        writer.line(f"__cw_native_{function.rust_symbol}(self, {right.rust_name})")
        writer.leave()
        writer.line("}")
        writer.leave()
        writer.line("}")
        writer.line()

    trait_groups: dict[tuple[str, str], list[FunctionIR]] = {}
    for function in package.functions:
        if function.method_for is None or function.trait_symbol is None:
            continue
        trait_groups.setdefault(
            (function.trait_symbol, function.method_for.rust_name), []
        ).append(function)
    for (trait_symbol, _), functions in trait_groups.items():
        target = functions[0].method_for
        assert target is not None
        writer.line(f"impl {trait_symbol} for {target.render()} {{")
        writer.enter()
        associated: dict[str, TypeRef] = {}

        def bind_associated(pattern: TypeRef, concrete: TypeRef) -> None:
            if pattern.rust_name == "Associated":
                assert pattern.python_name is not None
                previous = associated.get(pattern.python_name)
                if previous is not None and previous != concrete:
                    raise AssertionError("validated associated type mapping diverged")
                associated[pattern.python_name] = concrete
                return
            if len(pattern.arguments) != len(concrete.arguments):
                return
            for pattern_arg, concrete_arg in zip(
                pattern.arguments, concrete.arguments, strict=True
            ):
                bind_associated(pattern_arg, concrete_arg)

        trait = traits_by_symbol[trait_symbol]
        for function in functions:
            declared = next(
                method
                for method in trait.methods
                if method.name == function.method_name
            )
            bind_associated(declared.return_type, function.return_type)
            for pattern, parameter in zip(
                declared.parameter_types,
                function.parameters[1:],
                strict=True,
            ):
                bind_associated(pattern, parameter.type_ref)
        for name, type_ref in sorted(associated.items()):
            writer.line(f"type {name} = {type_ref.render()};")
        if associated:
            writer.line()
        for function in functions:
            assert function.method_name is not None
            _write_method_glue(
                writer,
                function,
                trait_method_names[(trait_symbol, function.method_name)],
            )
        writer.leave()
        writer.line("}")
        writer.line()


def _write_method_glue(
    writer: _Writer,
    function: FunctionIR,
    emitted_method_name: str | None = None,
) -> None:
    assert function.method_name is not None and function.parameters
    receiver_type = function.parameters[0].type_ref
    rendered_generics: list[str] = []
    for parameter in function.type_parameters:
        if parameter.is_lifetime:
            rendered_generics.append(f"'{parameter.rust_name}")
        else:
            qualified = tuple(
                {
                    "Clone": "std::clone::Clone",
                    "Copy": "std::marker::Copy",
                    "Debug": "std::fmt::Debug",
                    "Display": "std::fmt::Display",
                    "Ord": "std::cmp::Ord",
                    "PartialOrd": "std::cmp::PartialOrd",
                }.get(value, value)
                for value in parameter.bounds
            )
            bounds = f": {' + '.join(qualified)}" if qualified else ""
            rendered_generics.append(f"{parameter.rust_name}{bounds}")
    generics = f"<{', '.join(rendered_generics)}>" if rendered_generics else ""
    receiver = {
        "Ref": "&self",
        "Mut": "&mut self",
        "Owned": "self",
    }[receiver_type.rust_name]
    tail = [
        f"{parameter.rust_name}: {parameter.type_ref.render()}"
        for parameter in function.parameters[1:]
    ]
    parameters = ", ".join((receiver, *tail))
    arguments = ", ".join(
        ("self", *(parameter.rust_name for parameter in function.parameters[1:]))
    )
    return_type = (
        f"PyResult<{function.return_type.render()}>"
        if function.python_boundary
        else function.return_type.render()
    )
    writer.line(
        f"fn {emitted_method_name or function.method_name}{generics}({parameters}) "
        f"-> {return_type} {{",
        function.span,
        "method_impl",
    )
    writer.enter()
    writer.line(f"__cw_native_{function.rust_symbol}({arguments})")
    writer.leave()
    writer.line("}")


def _write_native_enum(writer: _Writer, enum: EnumIR) -> None:
    derives = (["Debug"] if enum.is_error else ["Clone", "Debug"]) + [
        "::".join(value) for value in enum.derives
    ]
    writer.line(f"#[derive({', '.join(derives)})]", enum.span, "enum_derive")
    writer.line(f"enum {enum.symbol} {{", enum.span, "enum")
    writer.enter()
    for variant in enum.variants:
        if not variant.fields:
            writer.line(f"{variant.rust_name},", variant.span, "enum_variant")
        elif variant.tuple_style:
            fields = ", ".join(field.type_ref.render() for field in variant.fields)
            writer.line(f"{variant.rust_name}({fields}),", variant.span, "enum_variant")
        else:
            writer.line(f"{variant.rust_name} {{", variant.span, "enum_variant")
            writer.enter()
            for field in variant.fields:
                writer.line(
                    f"{field.rust_name}: {field.type_ref.render()},",
                    field.span,
                    "enum_field",
                )
            writer.leave()
            writer.line("},")
    writer.leave()
    writer.line("}")


def _write_native_error_impls(writer: _Writer, enum: EnumIR) -> None:
    """Emit declared conversions and structured, source-preserving error metadata."""

    writer.line(f"impl std::fmt::Display for {enum.symbol} {{")
    writer.enter()
    writer.line(
        "fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {"
    )
    writer.enter()
    writer.line('write!(formatter, "{:?}", self)')
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line()

    writer.line(f"impl std::error::Error for {enum.symbol} {{")
    writer.enter()
    writer.line(
        "fn source(&self) -> std::option::Option<&(dyn std::error::Error + 'static)> {"
    )
    writer.enter()
    writer.line("match self {")
    writer.enter()
    for variant in enum.variants:
        source = variant.from_source
        if source is None or not (
            source.rust_name == "IoError" or _is_error_domain_type(source)
        ):
            continue
        source_binding = "__cw_source"
        pattern = _enum_variant_pattern(
            enum,
            variant.name,
            ((variant.fields[0].name, source_binding),),
            variant.tuple_style,
        )
        writer.line(f"{pattern} => std::option::Option::Some({source_binding}),")
    writer.line("_ => std::option::Option::None,")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line()

    for variant in enum.variants:
        source = variant.from_source
        if source is None:
            continue
        writer.line(f"impl std::convert::From<{source.render()}> for {enum.symbol} {{")
        writer.enter()
        writer.line(f"fn from(source: {source.render()}) -> Self {{")
        writer.enter()
        writer.line(f"Self::{variant.rust_name}(source)")
        writer.leave()
        writer.line("}")
        writer.leave()
        writer.line("}")
        writer.line()

    writer.line(f"impl {enum.symbol} {{")
    writer.enter()
    writer.line("fn __cw_variant(&self) -> &'static str {")
    writer.enter()
    writer.line("match self {")
    writer.enter()
    for variant in enum.variants:
        pattern = _enum_variant_pattern(enum, variant.name, (), variant.tuple_style)
        writer.line(f'{pattern} => "{variant.name}",')
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line()

    writer.line("fn __cw_fields(&self) -> Vec<(String, String)> {")
    writer.enter()
    writer.line("match self {")
    writer.enter()
    for variant_index, variant in enumerate(enum.variants):
        bindings = tuple(
            (field.name, f"__cw_field_{variant_index}_{field_index}")
            for field_index, field in enumerate(variant.fields)
        )
        pattern = _enum_variant_pattern(
            enum,
            variant.name,
            bindings,
            variant.tuple_style,
        )
        if not variant.fields:
            writer.line(f"{pattern} => Vec::new(),")
            continue
        values = ", ".join(
            (
                f'(String::from("{_error_field_name(variant, field.name)}"), '
                f'format!("{{}}", {binding}))'
            )
            for field, (_, binding) in zip(variant.fields, bindings)
        )
        writer.line(f"{pattern} => vec![{values}],")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line()

    writer.line("fn __cw_sources(&self) -> Vec<(String, String)> {")
    writer.enter()
    writer.line("match self {")
    writer.enter()
    for variant in enum.variants:
        source = variant.from_source
        if source is None:
            continue
        source_binding = "__cw_source"
        pattern = _enum_variant_pattern(
            enum,
            variant.name,
            ((variant.fields[0].name, source_binding),),
            variant.tuple_style,
        )
        source_type = json.dumps(source.display())
        if _is_error_domain_type(source):
            writer.line(f"{pattern} => {{")
            writer.enter()
            writer.line(
                f"let mut __cw_sources = vec![(String::from({source_type}), "
                f"{source_binding}.to_string())];"
            )
            writer.line(f"__cw_sources.extend({source_binding}.__cw_sources());")
            writer.line("__cw_sources")
            writer.leave()
            writer.line("},")
        else:
            writer.line(
                f"{pattern} => vec![(String::from({source_type}), "
                f"{source_binding}.to_string())],"
            )
    writer.line("_ => Vec::new(),")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")


def _is_error_domain_type(type_ref: TypeRef) -> bool:
    from .types import ErrorDomainType

    return isinstance(type_ref, ErrorDomainType)


def _error_field_name(variant: object, field_name: str) -> str:
    from_source = getattr(variant, "from_source", None)
    return "source" if from_source is not None and field_name == "_0" else field_name


def _domain_class(
    type_ref: TypeRef,
    domains_by_symbol: dict[str, TypeRef],
) -> str | None:
    domain = domains_by_symbol.get(type_ref.rust_name)
    return owned_class_names(domain)[1] if domain is not None else None


def _contains_domain(
    type_ref: TypeRef,
    domains_by_symbol: dict[str, TypeRef],
) -> bool:
    return _domain_class(type_ref, domains_by_symbol) is not None or any(
        _contains_domain(value, domains_by_symbol) for value in type_ref.arguments
    )


def _domain_input_type(
    type_ref: TypeRef,
    domains_by_symbol: dict[str, TypeRef],
) -> str:
    domain_class = _domain_class(type_ref, domains_by_symbol)
    if domain_class is not None:
        return f"PyRef<'_, {domain_class}>"
    if type_ref.rust_name == "Vec" and len(type_ref.arguments) == 1:
        return f"Vec<{_domain_input_type(type_ref.arguments[0], domains_by_symbol)}>"
    if type_ref.rust_name == "Option" and len(type_ref.arguments) == 1:
        return f"Option<{_domain_input_type(type_ref.arguments[0], domains_by_symbol)}>"
    if type_ref.rust_name == "Tuple" and type_ref.arguments:
        values = ", ".join(
            _domain_input_type(value, domains_by_symbol) for value in type_ref.arguments
        )
        return f"({values}{',' if len(type_ref.arguments) == 1 else ''})"
    if type_ref.rust_name == "HashMap" and len(type_ref.arguments) == 2:
        key, value = type_ref.arguments
        return (
            "std::collections::HashMap<"
            f"{_domain_input_type(key, domains_by_symbol)}, "
            f"{_domain_input_type(value, domains_by_symbol)}>"
        )
    return type_ref.render()


def _domain_input_conversion(
    expression: str,
    type_ref: TypeRef,
    domains_by_symbol: dict[str, TypeRef],
    names: EmissionNames,
    field_name: str,
) -> str:
    if _domain_class(type_ref, domains_by_symbol) is not None:
        return (
            f"{expression}.value.as_ref().cloned().ok_or_else(|| "
            f"{_native_move_error(field_name)})"
        )
    if type_ref.rust_name == "Vec" and len(type_ref.arguments) == 1:
        item = names.temporary("domain_input_item")
        child = _domain_input_conversion(
            item,
            type_ref.arguments[0],
            domains_by_symbol,
            names,
            field_name,
        )
        return (
            f"{expression}.into_iter().map(|{item}| {child})"
            ".collect::<PyResult<Vec<_>>>()"
        )
    if type_ref.rust_name == "Option" and len(type_ref.arguments) == 1:
        item = names.temporary("domain_input_item")
        child = _domain_input_conversion(
            item,
            type_ref.arguments[0],
            domains_by_symbol,
            names,
            field_name,
        )
        return (
            f"match {expression} {{ std::option::Option::Some({item}) => "
            f"({child}).map(std::option::Option::Some), "
            "std::option::Option::None => "
            "std::result::Result::<_, pyo3::PyErr>::Ok("
            "std::option::Option::None) }"
        )
    if type_ref.rust_name == "Tuple" and type_ref.arguments:
        values = ", ".join(
            f"({_domain_input_conversion(f'({expression}).{index}', child, domains_by_symbol, names, field_name)})?"
            for index, child in enumerate(type_ref.arguments)
        )
        suffix = "," if len(type_ref.arguments) == 1 else ""
        return f"std::result::Result::<_, pyo3::PyErr>::Ok(({values}{suffix}))"
    if type_ref.rust_name == "HashMap" and len(type_ref.arguments) == 2:
        key_name = names.temporary("domain_input_key")
        value_name = names.temporary("domain_input_value")
        key = _domain_input_conversion(
            key_name,
            type_ref.arguments[0],
            domains_by_symbol,
            names,
            field_name,
        )
        value = _domain_input_conversion(
            value_name,
            type_ref.arguments[1],
            domains_by_symbol,
            names,
            field_name,
        )
        return (
            f"{expression}.into_iter().map(|({key_name}, {value_name})| "
            f"std::result::Result::<_, pyo3::PyErr>::Ok((({key})?, ({value})?)))"
            ".collect::<PyResult<std::collections::HashMap<_, _>>>()"
        )
    return f"std::result::Result::<_, pyo3::PyErr>::Ok({expression})"


def _domain_output_type(
    type_ref: TypeRef,
    domains_by_symbol: dict[str, TypeRef],
) -> str:
    domain_class = _domain_class(type_ref, domains_by_symbol)
    if domain_class is not None:
        return f"Py<{domain_class}>"
    if type_ref.rust_name == "Vec" and len(type_ref.arguments) == 1:
        return f"Vec<{_domain_output_type(type_ref.arguments[0], domains_by_symbol)}>"
    if type_ref.rust_name == "Option" and len(type_ref.arguments) == 1:
        return (
            f"Option<{_domain_output_type(type_ref.arguments[0], domains_by_symbol)}>"
        )
    if type_ref.rust_name == "Tuple" and type_ref.arguments:
        values = ", ".join(
            _domain_output_type(value, domains_by_symbol)
            for value in type_ref.arguments
        )
        return f"({values}{',' if len(type_ref.arguments) == 1 else ''})"
    if type_ref.rust_name == "HashMap" and len(type_ref.arguments) == 2:
        key, value = type_ref.arguments
        return (
            "std::collections::HashMap<"
            f"{_domain_output_type(key, domains_by_symbol)}, "
            f"{_domain_output_type(value, domains_by_symbol)}>"
        )
    return type_ref.render()


def _domain_output_conversion(
    expression: str,
    type_ref: TypeRef,
    domains_by_symbol: dict[str, TypeRef],
    names: EmissionNames,
) -> str:
    domain_class = _domain_class(type_ref, domains_by_symbol)
    if domain_class is not None:
        return (
            f"Py::new(py, {domain_class} {{ value: "
            f"std::option::Option::Some((*({expression})).clone()) }})"
        )
    if type_ref.rust_name == "Vec" and len(type_ref.arguments) == 1:
        item = names.temporary("domain_output_item")
        child = _domain_output_conversion(
            item,
            type_ref.arguments[0],
            domains_by_symbol,
            names,
        )
        return (
            f"({expression}).iter().map(|{item}| {child}).collect::<PyResult<Vec<_>>>()"
        )
    if type_ref.rust_name == "Option" and len(type_ref.arguments) == 1:
        item = names.temporary("domain_output_item")
        child = _domain_output_conversion(
            item,
            type_ref.arguments[0],
            domains_by_symbol,
            names,
        )
        return f"({expression}).as_ref().map(|{item}| {child}).transpose()"
    if type_ref.rust_name == "Tuple" and type_ref.arguments:
        values = ", ".join(
            f"({_domain_output_conversion(f'&({expression}).{index}', child, domains_by_symbol, names)})?"
            for index, child in enumerate(type_ref.arguments)
        )
        suffix = "," if len(type_ref.arguments) == 1 else ""
        return f"std::result::Result::<_, pyo3::PyErr>::Ok(({values}{suffix}))"
    if type_ref.rust_name == "HashMap" and len(type_ref.arguments) == 2:
        key_name = names.temporary("domain_output_key")
        value_name = names.temporary("domain_output_value")
        key = _domain_output_conversion(
            key_name,
            type_ref.arguments[0],
            domains_by_symbol,
            names,
        )
        value = _domain_output_conversion(
            value_name,
            type_ref.arguments[1],
            domains_by_symbol,
            names,
        )
        return (
            f"({expression}).iter().map(|({key_name}, {value_name})| "
            f"std::result::Result::<_, pyo3::PyErr>::Ok((({key})?, ({value})?)))"
            ".collect::<PyResult<std::collections::HashMap<_, _>>>()"
        )
    return f"std::result::Result::<_, pyo3::PyErr>::Ok((*({expression})).clone())"


def _write_owned_enum_class(
    writer: _Writer,
    enum: EnumIR,
    domains_by_symbol: dict[str, TypeRef],
) -> None:
    python_name, rust_name = owned_class_names(enum.type_ref)
    writer.line(f'#[pyclass(name = "{python_name}")]')
    writer.line(f"struct {rust_name} {{")
    writer.enter()
    writer.line(f"value: Option<{enum.symbol}>,")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("#[pymethods]")
    writer.line("#[allow(non_snake_case)]")
    writer.line(f"impl {rust_name} {{")
    writer.enter()

    for variant in enum.variants:
        constructor_names = EmissionNames.reserving(
            *(field.rust_name for field in variant.fields)
        )
        extracted_fields: dict[str, str] = {}
        parameters = ", ".join(
            f"{field.rust_name}: "
            f"{_domain_input_type(field.type_ref, domains_by_symbol)}"
            for field in variant.fields
        )
        fallible = any(
            _contains_domain(field.type_ref, domains_by_symbol)
            for field in variant.fields
        )
        writer.line("#[staticmethod]")
        return_type = "PyResult<Self>" if fallible else "Self"
        if variant.rust_name != variant.name:
            writer.line(f'#[pyo3(name = "{variant.name}")]')
        writer.line(f"fn {variant.rust_name}({parameters}) -> {return_type} {{")
        writer.enter()
        for field in variant.fields:
            if not _contains_domain(field.type_ref, domains_by_symbol):
                continue
            extracted_field = constructor_names.temporary(f"field_{field.name}")
            extracted_fields[field.name] = extracted_field
            writer.line(
                f"let {extracted_field}: {field.type_ref.render()} = "
                f"{_domain_input_conversion(field.rust_name, field.type_ref, domains_by_symbol, constructor_names, field.name)}?;"
            )
        if not variant.fields:
            value = f"{enum.symbol}::{variant.rust_name}"
        elif variant.tuple_style:
            arguments = ", ".join(
                (
                    extracted_fields[field.name]
                    if _contains_domain(field.type_ref, domains_by_symbol)
                    else field.rust_name
                )
                for field in variant.fields
            )
            value = f"{enum.symbol}::{variant.rust_name}({arguments})"
        else:
            arguments = ", ".join(
                (
                    f"{field.rust_name}: {extracted_fields[field.name]}"
                    if _contains_domain(field.type_ref, domains_by_symbol)
                    else f"{field.rust_name}: {field.rust_name}"
                )
                for field in variant.fields
            )
            value = f"{enum.symbol}::{variant.rust_name} {{ {arguments} }}"
        wrapped = f"Self {{ value: std::option::Option::Some({value}) }}"
        writer.line(f"std::result::Result::Ok({wrapped})" if fallible else wrapped)
        writer.leave()
        writer.line("}")
        writer.line()
    writer.line("fn variant(&self) -> PyResult<&'static str> {")
    writer.enter()
    writer.line("match self.value.as_ref() {")
    writer.enter()
    for variant in enum.variants:
        pattern = _enum_variant_pattern(enum, variant.name, (), variant.tuple_style)
        writer.line(
            f"std::option::Option::Some({pattern}) => "
            f'std::result::Result::Ok("{variant.name}"),'
        )
    writer.line(
        f"std::option::Option::None => std::result::Result::Err("
        f"{_native_move_error('')}),"
    )
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    field_types: dict[str, set[TypeRef]] = {}
    for variant in enum.variants:
        for field in variant.fields:
            field_types.setdefault(field.name, set()).add(field.type_ref)
    for field_name, candidate_types in sorted(field_types.items()):
        heterogeneous = len(candidate_types) > 1
        field_type = next(iter(candidate_types))
        nested_domain = (
            _contains_domain(field_type, domains_by_symbol)
            if not heterogeneous
            else False
        )
        getter_names = EmissionNames.reserving("self", "py")
        stored_value = getter_names.temporary("stored_value")
        target_name = getter_names.temporary("variant_target")
        getter_field = next(
            field
            for variant in enum.variants
            for field in variant.fields
            if field.name == field_name
        )
        writer.line()
        writer.line(f'#[getter("{field_name}")]')
        if heterogeneous:
            writer.line(
                f"fn get_{getter_field.rust_name}(&self, py: Python<'_>) -> "
                "PyResult<Option<Py<PyAny>>> {"
            )
        elif nested_domain:
            writer.line(
                f"fn get_{getter_field.rust_name}(&self, py: Python<'_>) -> "
                f"PyResult<Option<{_domain_output_type(field_type, domains_by_symbol)}>> {{"
            )
        else:
            writer.line(
                f"fn get_{getter_field.rust_name}(&self) "
                f"-> PyResult<Option<{field_type.render()}>> {{"
            )
        writer.enter()
        writer.line(f"let {stored_value} = self.value.as_ref().ok_or_else(|| {{")
        writer.enter()
        writer.line(_native_move_error(""))
        writer.leave()
        writer.line("})?;")
        writer.line(f"match {stored_value} {{")
        writer.enter()
        for variant in enum.variants:
            target = next(
                (field for field in variant.fields if field.name == field_name), None
            )
            if target is None:
                continue
            bindings = tuple(
                (field.name, target_name if field.name == field_name else "")
                for field in variant.fields
            )
            pattern = _enum_variant_pattern(
                enum,
                variant.name,
                bindings,
                variant.tuple_style,
            )
            target_has_domain = _contains_domain(target.type_ref, domains_by_symbol)
            if target_has_domain:
                native = _domain_output_conversion(
                    target_name,
                    target.type_ref,
                    domains_by_symbol,
                    getter_names,
                )
                converted = (
                    f"({native})?.into_py_any(py)?" if heterogeneous else f"({native})?"
                )
            else:
                converted = (
                    f"{target_name}.clone().into_py_any(py)?"
                    if heterogeneous
                    else f"{target_name}.clone()"
                )
            writer.line(
                f"{pattern} => std::result::Result::Ok("
                f"std::option::Option::Some({converted})),"
            )
        writer.line("_ => std::result::Result::Ok(std::option::Option::None),")
        writer.leave()
        writer.line("}")
        writer.leave()
        writer.line("}")
    writer.line()
    writer.line("fn is_moved(&self) -> bool {")
    writer.enter()
    writer.line("self.value.is_none()")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("fn __repr__(&self) -> String {")
    writer.enter()
    writer.line("match &self.value {")
    writer.enter()
    writer.line(
        f'std::option::Option::Some(value) => format!("{enum.name}({{:?}})", value),'
    )
    writer.line(f'std::option::Option::None => String::from("{enum.name}(<moved>)"),')
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")


def _enum_has_heterogeneous_fields(enum: EnumIR) -> bool:
    """Return whether one Python-visible payload name has multiple Rust types.

    Rust tuple variants conventionally reuse positional names such as ``_0`` even
    though each variant is free to choose an unrelated payload type. PyO3 needs a
    single return type for a Python property, so those getters erase only the ABI
    representation to ``PyAny`` while the native enum remains fully typed.
    """

    field_types: dict[str, set[TypeRef]] = {}
    for variant in enum.variants:
        for field in variant.fields:
            field_types.setdefault(field.name, set()).add(field.type_ref)
    return any(len(value) > 1 for value in field_types.values())


def _enum_variant_pattern(
    enum: EnumIR,
    variant_name: str,
    bindings: tuple[tuple[str, str], ...],
    tuple_style: bool,
) -> str:
    variant = next(value for value in enum.variants if value.name == variant_name)
    if not variant.fields:
        return f"{enum.symbol}::{variant.rust_name}"
    values = {field: local for field, local in bindings}
    if tuple_style:
        patterns = ", ".join(values.get(field.name) or "_" for field in variant.fields)
        return f"{enum.symbol}::{variant.rust_name}({patterns})"
    patterns = ", ".join(
        f"{field.rust_name}: {values.get(field.name) or '_'}"
        for field in variant.fields
    )
    return f"{enum.symbol}::{variant.rust_name} {{ {patterns} }}"


def _write_owned_struct_class(
    writer: _Writer,
    struct: StructIR,
    domains_by_symbol: dict[str, TypeRef],
) -> None:
    python_name, rust_name = owned_class_names(struct.type_ref)
    writer.line(f'#[pyclass(name = "{python_name}")]')
    writer.line(f"struct {rust_name} {{")
    writer.enter()
    writer.line(f"value: Option<{struct.symbol}>,")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("#[pymethods]")
    writer.line(f"impl {rust_name} {{")
    writer.enter()

    parameters = ", ".join(
        f"{field.rust_name}: {_domain_input_type(field.type_ref, domains_by_symbol)}"
        for field in struct.fields
    )
    writer.line("#[new]")
    writer.line(f"fn new({parameters}) -> PyResult<Self> {{")
    writer.enter()
    constructor_names = EmissionNames.reserving(
        *(field.rust_name for field in struct.fields)
    )
    extracted_fields: dict[str, str] = {}
    for field in struct.fields:
        if not _contains_domain(field.type_ref, domains_by_symbol):
            continue
        extracted_field = constructor_names.temporary(f"field_{field.name}")
        extracted_fields[field.name] = extracted_field
        writer.line(
            f"let {extracted_field}: {field.type_ref.render()} = "
            f"{_domain_input_conversion(field.rust_name, field.type_ref, domains_by_symbol, constructor_names, field.name)}?;"
        )
    writer.line(
        "std::result::Result::Ok(Self { value: std::option::Option::Some("
        + struct.symbol
        + " {"
    )
    writer.enter()
    for field in struct.fields:
        value = (
            extracted_fields[field.name]
            if _contains_domain(field.type_ref, domains_by_symbol)
            else field.rust_name
        )
        writer.line(f"{field.rust_name}: {value},")
    writer.leave()
    writer.line("}) })")
    writer.leave()
    writer.line("}")
    for field in struct.fields:
        nested_domain = _contains_domain(field.type_ref, domains_by_symbol)
        getter_names = EmissionNames.reserving("self", "py")
        stored_value = getter_names.temporary("stored_value")
        writer.line()
        writer.line(f'#[getter("{field.name}")]')
        if not nested_domain:
            writer.line(
                f"fn get_{field.rust_name}(&self) "
                f"-> PyResult<{field.type_ref.render()}> {{"
            )
        else:
            writer.line(
                f"fn get_{field.rust_name}(&self, py: Python<'_>) -> "
                f"PyResult<{_domain_output_type(field.type_ref, domains_by_symbol)}> {{"
            )
        writer.enter()
        writer.line(f"let {stored_value} = self.value.as_ref().ok_or_else(|| {{")
        writer.enter()
        writer.line(_native_move_error(""))
        writer.leave()
        writer.line("})?;")
        if not nested_domain:
            writer.line(
                f"std::result::Result::Ok({stored_value}.{field.rust_name}.clone())"
            )
        else:
            writer.line(
                _domain_output_conversion(
                    f"&{stored_value}.{field.rust_name}",
                    field.type_ref,
                    domains_by_symbol,
                    getter_names,
                )
            )
        writer.leave()
        writer.line("}")
        writer.line()
        writer.line(f'#[setter("{field.name}")]')
        setter_type = _domain_input_type(field.type_ref, domains_by_symbol)
        writer.line(
            f"fn set_{field.rust_name}(&mut self, value: {setter_type}) "
            "-> PyResult<()> {"
        )
        writer.enter()
        setter_names = EmissionNames.reserving("self", "value")
        assigned_value = "value"
        if nested_domain:
            assigned_value = setter_names.temporary("assigned_value")
            writer.line(
                f"let {assigned_value}: {field.type_ref.render()} = "
                f"{_domain_input_conversion('value', field.type_ref, domains_by_symbol, setter_names, field.name)}?;"
            )
        target = setter_names.temporary("target")
        writer.line(f"let {target} = self.value.as_mut().ok_or_else(|| {{")
        writer.enter()
        writer.line(_native_move_error(""))
        writer.leave()
        writer.line("})?;")
        writer.line(f"{target}.{field.rust_name} = {assigned_value};")
        writer.line("std::result::Result::Ok(())")
        writer.leave()
        writer.line("}")
    writer.line()
    writer.line(
        "fn to_python(&self, py: Python<'_>) -> PyResult<Py<pyo3::types::PyTuple>> {",
        struct.span,
        "struct_to_python",
    )
    writer.enter()
    to_python_names = EmissionNames.reserving("self", "py")
    stored_value = to_python_names.temporary("stored_value")
    items = to_python_names.temporary("python_items")
    writer.line(f"let {stored_value} = self.value.as_ref().ok_or_else(|| {{")
    writer.enter()
    writer.line(_native_move_error(""))
    writer.leave()
    writer.line("})?;")
    converted_fields: dict[str, str] = {}
    for field in struct.fields:
        if not _contains_domain(field.type_ref, domains_by_symbol):
            continue
        converted = to_python_names.temporary(f"python_field_{field.name}")
        converted_fields[field.name] = converted
        writer.line(
            f"let {converted} = "
            f"{_domain_output_conversion(f'&{stored_value}.{field.rust_name}', field.type_ref, domains_by_symbol, to_python_names)}?;"
        )
    writer.line(f"let {items}: Vec<Py<PyAny>> = vec![")
    writer.enter()
    for field in struct.fields:
        if field.name in converted_fields:
            converted = f"{converted_fields[field.name]}.into_py_any(py)?,"
        else:
            converted = f"{stored_value}.{field.rust_name}.clone().into_py_any(py)?,"
        writer.line(converted, field.span, "struct_field_to_python")
    writer.leave()
    writer.line("];")
    writer.line(
        f"std::result::Result::Ok(pyo3::types::PyTuple::new(py, {items})?.unbind())"
    )
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("fn is_moved(&self) -> bool {")
    writer.enter()
    writer.line("self.value.is_none()")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("fn __repr__(&self) -> String {")
    writer.enter()
    writer.line("match &self.value {")
    writer.enter()
    writer.line(
        f'std::option::Option::Some(value) => format!("{struct.name}({{:?}})", value),'
    )
    writer.line(f'std::option::Option::None => String::from("{struct.name}(<moved>)"),')
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")


def _write_export_wrapper(
    writer: _Writer,
    function: FunctionIR,
    boundary_names: set[str],
    error_enums_by_symbol: dict[str, EnumIR],
) -> None:
    emission_names = EmissionNames.for_function(function)
    wrapper_parameters = [
        _wrapper_parameter(parameter) for parameter in function.parameters
    ]
    releases_gil = function_releases_gil(function)
    has_buffer = any(
        parameter.type_ref.underlying.rust_name == "Buffer"
        for parameter in function.parameters
    )
    needs_python_token = releases_gil or has_buffer
    python_token = (
        emission_names.temporary("python_token") if needs_python_token else None
    )
    if needs_python_token:
        assert python_token is not None
        wrapper_parameters.insert(0, f"{python_token}: Python<'_>")
    parameters = ", ".join(wrapper_parameters)
    extracted_arguments = {
        parameter.rust_name: emission_names.temporary(f"argument_{parameter.name}")
        for parameter in function.parameters
        if parameter.type_ref.ownership is not None
        or parameter.type_ref.underlying.rust_name == "Buffer"
    }
    untyped_buffers = {
        parameter.rust_name: emission_names.temporary(
            f"untyped_buffer_{parameter.name}"
        )
        for parameter in function.parameters
        if parameter.type_ref.ownership is None
        and parameter.type_ref.rust_name == "Buffer"
    }
    arguments = ", ".join(
        (
            extracted_arguments[parameter.rust_name]
            if parameter.rust_name in extracted_arguments
            else parameter.rust_name
        )
        for parameter in function.parameters
    )
    writer.line("#[pyfunction]")
    owned_return = function.return_type.ownership == "Owned"
    if owned_return:
        _, return_class = owned_class_names(function.return_type.underlying)
        wrapper_return = f"PyResult<{return_class}>"
    else:
        wrapper_return = (
            f"PyResult<{function.return_type.arguments[0].render()}>"
            if function.return_type.rust_name == "Result"
            else f"PyResult<{function.return_type.render()}>"
        )
    writer.line(
        f"fn {function.rust_symbol}({parameters}) -> {wrapper_return} {{",
        function.span,
        "abi_wrapper",
    )
    writer.enter()
    for parameter in function.parameters:
        _write_wrapper_ownership_preflight(writer, parameter)
    for parameter in function.parameters:
        _write_wrapper_buffer_preflight(
            writer,
            parameter,
            untyped_buffers.get(parameter.rust_name),
        )
    for parameter in function.parameters:
        _write_wrapper_extraction(
            writer,
            parameter,
            extracted_arguments.get(parameter.rust_name),
            python_token,
            untyped_buffers.get(parameter.rust_name),
        )
    if releases_gil:
        for parameter in function.parameters:
            if parameter.type_ref.ownership in {"Owned", "Shared"}:
                writer.line(
                    f"drop({parameter.rust_name});",
                    parameter.span,
                    "gil_release_guard_drop",
                )
    if owned_return:
        native_call = f"__cw_native_{function.rust_symbol}({arguments})"
        if releases_gil:
            assert python_token is not None
            native_call = f"{python_token}.detach(move || {native_call})"
        caught_result = emission_names.temporary("caught_result")
        writer.line(
            f"let {caught_result} = __cw_catch_panic(|| {native_call})?;",
            function.span,
            "panic_boundary",
        )
        final_result = caught_result
        if function.python_boundary:
            final_result = emission_names.temporary("python_result")
            writer.line(f"let {final_result} = {caught_result}?;")
        writer.line(
            "std::result::Result::Ok("
            f"{return_class} {{ value: std::option::Option::Some({final_result}) }})"
        )
    elif function.return_type.rust_name == "Result":
        native_call = f"__cw_native_{function.rust_symbol}({arguments})"
        if releases_gil:
            assert python_token is not None
            native_call = f"{python_token}.detach(move || {native_call})"
        caught_result = emission_names.temporary("caught_result")
        writer.line(
            f"let {caught_result} = __cw_catch_panic(|| {native_call})?;",
            function.span,
            "panic_boundary",
        )
        final_result = caught_result
        if function.python_boundary:
            final_result = emission_names.temporary("python_result")
            writer.line(f"let {final_result} = {caught_result}?;")
        writer.line(
            f"match {final_result} {{",
            function.span,
            "abi_call",
        )
        writer.enter()
        writer.line("std::result::Result::Ok(value) => std::result::Result::Ok(value),")
        error_ref = function.return_type.arguments[1]
        error_type = error_ref.display()
        error_enum = error_enums_by_symbol.get(error_ref.rust_name)
        if error_enum is None:
            writer.line(
                "std::result::Result::Err(error) => std::result::Result::Err("
                "__CwNativeRustResultError::new_err(("
                f"{json.dumps(error_type)}, error.to_string()))),"
            )
        else:
            writer.line(
                "std::result::Result::Err(error) => {",
                error_enum.span,
                "structured_error_boundary",
            )
            writer.enter()
            writer.line("let __cw_message = error.to_string();")
            writer.line("let __cw_variant = error.__cw_variant();")
            writer.line("let __cw_fields = error.__cw_fields();")
            writer.line("let __cw_sources = error.__cw_sources();")
            writer.line(
                "std::result::Result::Err(__CwNativeRustResultError::new_err(("
                f"{json.dumps(error_type)}, __cw_message, __cw_variant, "
                "__cw_fields, __cw_sources)))"
            )
            writer.leave()
            writer.line("},")
        writer.leave()
        writer.line("}")
    elif function.python_boundary:
        writer.line(
            (f"__cw_catch_panic(|| __cw_native_{function.rust_symbol}({arguments}))?"),
            function.span,
            "abi_call",
        )
    else:
        native_call = f"__cw_native_{function.rust_symbol}({arguments})"
        if releases_gil:
            assert python_token is not None
            native_call = f"{python_token}.detach(move || {native_call})"
        writer.line(
            f"std::result::Result::Ok(__cw_catch_panic(|| {native_call})?)",
            function.span,
            "abi_call",
        )
    writer.leave()
    writer.line("}")


