    writer.line("#[pymethods]")
    writer.line(f"impl {rust_name} {{")
    writer.enter()
    writer.line("#[new]")
    writer.line(
        f"fn new(mut source: PyRefMut<'_, {owned_rust_name}>) -> PyResult<Self> {{"
    )
    writer.enter()
