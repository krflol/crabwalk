def _write_thread_pool(writer: _Writer) -> None:
    writer.line("type __CwJob = Box<dyn FnOnce() + Send + 'static>;")
    writer.line(
        "type __CwWorkerFailure = std::sync::Arc<std::sync::Mutex<Option<String>>>;"
    )
    writer.line()
    writer.line(
        "fn __cw_record_worker_failure(failure: &__CwWorkerFailure, message: String) {"
    )
    writer.enter()
    writer.line(
        "let mut slot = failure.lock().unwrap_or_else(|poisoned| poisoned.into_inner());"
    )
    writer.line("if slot.is_none() { *slot = std::option::Option::Some(message); }")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("struct __CwThreadPool {")
    writer.enter()
    writer.line("workers: Vec<__CwWorker>,")
    writer.line("sender: Option<std::sync::mpsc::Sender<__CwJob>>,")
    writer.line("failure: __CwWorkerFailure,")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("impl __CwThreadPool {")
    writer.enter()
    writer.line("fn new(size: usize) -> Self {")
    writer.enter()
    writer.line('assert!(size > 0, "thread pool size must be positive");')
    writer.line("let (sender, receiver) = std::sync::mpsc::channel();")
    writer.line("let receiver = std::sync::Arc::new(std::sync::Mutex::new(receiver));")
    writer.line("let failure = std::sync::Arc::new(std::sync::Mutex::new(None));")
    writer.line("let mut workers = Vec::with_capacity(size);")
    writer.line("for id in 0..size {")
    writer.enter()
    writer.line(
        "workers.push(__CwWorker::new(id, std::sync::Arc::clone(&receiver), "
        "std::sync::Arc::clone(&failure)));"
    )
    writer.leave()
    writer.line("}")
    writer.line("Self { workers, sender: std::option::Option::Some(sender), failure }")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("fn execute<F>(&self, operation: F)")
    writer.line("where")
    writer.enter()
    writer.line("F: FnOnce() + Send + 'static,")
    writer.leave()
    writer.line("{")
    writer.enter()
    writer.line("let job = Box::new(operation);")
    writer.line("self.sender.as_ref().unwrap().send(job).unwrap();")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("fn finish(mut self) -> Result<(), String> {")
    writer.enter()
    writer.line("self.shutdown();")
    writer.line("let failure = {")
    writer.enter()
    writer.line(
        "let mut slot = self.failure.lock()"
        ".unwrap_or_else(|poisoned| poisoned.into_inner());"
    )
    writer.line("slot.take()")
    writer.leave()
    writer.line("};")
    writer.line(
        "match failure { "
        "std::option::Option::Some(message) => std::result::Result::Err(message), "
        "std::option::Option::None => std::result::Result::Ok(()) }"
    )
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("fn shutdown(&mut self) {")
    writer.enter()
    writer.line("drop(self.sender.take());")
    writer.line("for worker in self.workers.drain(..) {")
    writer.enter()
    writer.line("if let std::result::Result::Err(payload) = worker.thread.join() {")
    writer.enter()
    writer.line(
        "__cw_record_worker_failure(&self.failure, __cw_panic_message(payload));"
    )
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("impl Drop for __CwThreadPool {")
    writer.enter()
    writer.line("fn drop(&mut self) {")
    writer.enter()
    writer.line("self.shutdown();")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("struct __CwWorker {")
    writer.enter()
    writer.line("_id: usize,")
    writer.line("thread: std::thread::JoinHandle<()>,")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("impl __CwWorker {")
    writer.enter()
    writer.line(
        "fn new(id: usize, receiver: "
        "std::sync::Arc<std::sync::Mutex<std::sync::mpsc::Receiver<__CwJob>>>, "
        "failure: __CwWorkerFailure) "
        "-> Self {"
    )
    writer.enter()
    writer.line("let thread = std::thread::spawn(move || loop {")
    writer.enter()
    writer.line("let message = receiver.lock()")
    writer.enter()
    writer.line(".unwrap_or_else(|poisoned| poisoned.into_inner())")
    writer.line(".recv();")
    writer.leave()
    writer.line("match message {")
    writer.enter()
    writer.line("std::result::Result::Ok(job) => {")
    writer.enter()
    writer.line(
        "if let std::result::Result::Err(payload) = std::panic::catch_unwind("
        "std::panic::AssertUnwindSafe(job)) {"
    )
    writer.enter()
    writer.line("__cw_record_worker_failure(&failure, __cw_panic_message(payload));")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line("std::result::Result::Err(_) => break,")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("});")
    writer.line("Self { _id: id, thread }")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")


def _write_block_on_executor(writer: _Writer) -> None:
    """Emit the minimal std-only executor used by explicit rust.block_on calls.

    It is intentionally educational rather than a replacement for Tokio or async-std:
    a pending future yields the OS thread and is polled again. The implementation is
    safe Rust, deterministic, and sufficient for the self-contained Book examples.
    """

    writer.line("struct __CwNoopWake;")
    writer.line("impl std::task::Wake for __CwNoopWake {")
    writer.enter()
    writer.line("fn wake(self: std::sync::Arc<Self>) {}")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("async fn __cw_yield_now() {")
    writer.enter()
    writer.line("let mut yielded = false;")
    writer.line("std::future::poll_fn(move |context| {")
    writer.enter()
    writer.line("if yielded {")
    writer.enter()
    writer.line("std::task::Poll::Ready(())")
    writer.leave()
    writer.line("} else {")
    writer.enter()
    writer.line("yielded = true;")
    writer.line("context.waker().wake_by_ref();")
    writer.line("std::task::Poll::Pending")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}).await")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("async fn __cw_sleep_millis(milliseconds: u64) {")
    writer.enter()
    writer.line(
        "let deadline = std::time::Instant::now() "
        "+ std::time::Duration::from_millis(milliseconds);"
    )
    writer.line("std::future::poll_fn(move |context| {")
    writer.enter()
    writer.line("if std::time::Instant::now() >= deadline {")
    writer.enter()
    writer.line("std::task::Poll::Ready(())")
    writer.leave()
    writer.line("} else {")
    writer.enter()
    writer.line("context.waker().wake_by_ref();")
    writer.line("std::task::Poll::Pending")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}).await")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("async fn __cw_join2<A: std::future::Future, B: std::future::Future>(")
    writer.enter()
    writer.line("left: A,")
    writer.line("right: B,")
    writer.leave()
    writer.line(") -> (A::Output, B::Output) {")
    writer.enter()
    writer.line("let mut left = std::pin::pin!(left);")
    writer.line("let mut right = std::pin::pin!(right);")
    writer.line("let mut left_output = None;")
    writer.line("let mut right_output = None;")
    writer.line("std::future::poll_fn(move |context| {")
    writer.enter()
    writer.line("if left_output.is_none() {")
    writer.enter()
    writer.line(
        "if let std::task::Poll::Ready(value) = "
        "std::future::Future::poll(left.as_mut(), context) {"
    )
    writer.enter()
    writer.line("left_output = std::option::Option::Some(value);")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line("if right_output.is_none() {")
    writer.enter()
    writer.line(
        "if let std::task::Poll::Ready(value) = "
        "std::future::Future::poll(right.as_mut(), context) {"
    )
    writer.enter()
    writer.line("right_output = std::option::Option::Some(value);")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.line("if left_output.is_some() && right_output.is_some() {")
    writer.enter()
    writer.line(
        "std::task::Poll::Ready((left_output.take().unwrap(), "
        "right_output.take().unwrap()))"
    )
    writer.leave()
    writer.line("} else {")
    writer.enter()
    writer.line("std::task::Poll::Pending")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}).await")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("async fn __cw_select2<A, B>(left: A, right: B) -> A::Output")
    writer.line("where")
    writer.enter()
    writer.line("A: std::future::Future,")
    writer.line("B: std::future::Future<Output = A::Output>,")
    writer.leave()
    writer.line("{")
    writer.enter()
    writer.line("let mut left = std::pin::pin!(left);")
    writer.line("let mut right = std::pin::pin!(right);")
    writer.line("std::future::poll_fn(move |context| {")
    writer.enter()
    writer.line(
        "if let std::task::Poll::Ready(value) = "
        "std::future::Future::poll(left.as_mut(), context) {"
    )
    writer.enter()
    writer.line("return std::task::Poll::Ready(value);")
    writer.leave()
    writer.line("}")
    writer.line(
        "if let std::task::Poll::Ready(value) = "
        "std::future::Future::poll(right.as_mut(), context) {"
    )
    writer.enter()
    writer.line("return std::task::Poll::Ready(value);")
    writer.leave()
    writer.line("}")
    writer.line("std::task::Poll::Pending")
    writer.leave()
    writer.line("}).await")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line(
        "async fn __cw_recv_async<T>(receiver: &std::sync::mpsc::Receiver<T>) -> T {"
    )
    writer.enter()
    writer.line("std::future::poll_fn(|context| match receiver.try_recv() {")
    writer.enter()
    writer.line("std::result::Result::Ok(value) => std::task::Poll::Ready(value),")
    writer.line("std::result::Result::Err(std::sync::mpsc::TryRecvError::Empty) => {")
    writer.enter()
    writer.line("context.waker().wake_by_ref();")
    writer.line("std::task::Poll::Pending")
    writer.leave()
    writer.line("}")
    writer.line(
        "std::result::Result::Err("
        "std::sync::mpsc::TryRecvError::Disconnected) => "
        'panic!("async channel disconnected"),'
    )
    writer.leave()
    writer.line("}).await")
    writer.leave()
    writer.line("}")
    writer.line()
    writer.line("fn __cw_block_on<F: std::future::Future>(future: F) -> F::Output {")
    writer.enter()
    writer.line(
        "let waker = std::task::Waker::from(std::sync::Arc::new(__CwNoopWake));"
    )
    writer.line("let mut context = std::task::Context::from_waker(&waker);")
    writer.line("let mut future = std::pin::pin!(future);")
    writer.line("loop {")
    writer.enter()
    writer.line("match std::future::Future::poll(future.as_mut(), &mut context) {")
    writer.enter()
    writer.line("std::task::Poll::Ready(value) => return value,")
    writer.line("std::task::Poll::Pending => std::thread::yield_now(),")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")
    writer.leave()
    writer.line("}")


def function_releases_gil(function: FunctionIR) -> bool:
    """Whether an exported wrapper can detach from Python for the native call."""

    effects = set(function.effects)
    if function.release_gil:
        return (
            function.exported
            and Effect.PYTHON_RUNTIME not in effects
            and all(
                not _type_retains_python_borrow_for_detach(parameter.type_ref)
                for parameter in function.parameters
            )
        )
    if effects & {
        Effect.BORROWED_BUFFER,
        Effect.OPAQUE_CRATE_CALL,
        Effect.PYTHON_RUNTIME,
        Effect.GLOBAL_MUTATION,
        Effect.UNSAFE_MEMORY,
        Effect.UNSAFE_FFI,
    }:
        return False
    if any(
        parameter.type_ref.ownership not in {None, "Shared"}
        for parameter in function.parameters
    ):
        return False
    safe_names = {
        "i8",
        "i16",
        "i32",
        "i64",
        "i128",
        "isize",
        "u8",
        "u16",
        "u32",
        "u64",
        "u128",
        "usize",
        "f32",
        "f64",
        "bool",
        "char",
        "Unit",
    }
    return (
        all(
            parameter.type_ref.rust_name in safe_names
            or parameter.type_ref.ownership == "Shared"
            for parameter in function.parameters
        )
        and function.return_type.rust_name in safe_names
    )


def _type_retains_python_borrow_for_detach(type_ref: TypeRef) -> bool:
    if type_ref.ownership in {"Owned", "Shared"}:
        return False
    if type_ref.ownership in {"Ref", "Mut"}:
        return True
    if type_ref.rust_name in {"Buffer", "Str", "LifetimeRef"}:
        return True
    return any(
        _type_retains_python_borrow_for_detach(value) for value in type_ref.arguments
    )


def _owned_vector_types(ir: PackageIR) -> tuple[TypeRef, ...]:
    values: dict[str, TypeRef] = {}
    for function in ir.functions:
        if not function.exported:
            continue
        for parameter in function.parameters:
            if (
                parameter.type_ref.ownership is not None
                and parameter.type_ref.underlying.rust_name == "Vec"
            ):
                vector = parameter.type_ref.underlying
                values[vector.render()] = vector
        if (
            function.return_type.ownership == "Owned"
            and function.return_type.underlying.rust_name == "Vec"
        ):
            vector = function.return_type.underlying
            values[vector.render()] = vector
    return tuple(values[key] for key in sorted(values))


def _owned_text_column_type(ir: PackageIR) -> TypeRef | None:
    for function in ir.functions:
        if not function.exported:
            continue
        if any(
            parameter.type_ref.ownership is not None
            and parameter.type_ref.underlying.rust_name == "TextColumn"
            for parameter in function.parameters
        ):
            return TypeRef("TextColumn")
        if (
            function.return_type.ownership == "Owned"
            and function.return_type.underlying.rust_name == "TextColumn"
        ):
            return TypeRef("TextColumn")
    return None


def _owned_external_types(ir: PackageIR) -> tuple[ExternalType, ...]:
    values: dict[str, ExternalType] = {}
    for function in ir.functions:
        if not function.exported:
            continue
        for parameter in function.parameters:
            underlying = parameter.type_ref.underlying
            if parameter.type_ref.ownership is not None and isinstance(
                underlying, ExternalType
            ):
                values[underlying.render()] = underlying
        return_type = function.return_type.underlying
        if function.return_type.ownership == "Owned" and isinstance(
            return_type, ExternalType
        ):
            values[return_type.render()] = return_type
    return tuple(values[key] for key in sorted(values))


