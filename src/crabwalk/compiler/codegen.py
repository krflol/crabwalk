    writer.leave()
    writer.line("}")
    writer.line("fn __len__(&self) -> PyResult<usize> {")
    writer.enter()
    writer.line("self.value.as_ref().map(__CwTextColumn::len).ok_or_else(|| {")
    writer.enter()
    writer.line(_native_move_error(""))
    writer.leave()
